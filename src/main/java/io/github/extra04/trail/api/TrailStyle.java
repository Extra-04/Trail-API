package io.github.extra04.trail.api;

/**
 * 잔상이 어떤 모양으로 남는지.
 *
 * <p>잔상 정의 파일의 {@code style} 값에 대응한다. 나중에 새 스타일이 생길 수 있으므로
 * {@code switch} 에는 항상 기본 분기를 두는 것이 안전하다.
 */
public enum TrailStyle {
    /** 아이템 하나(또는 여러 개)가 남는다. */
    ITEM,
    /** 플레이어 몸 모양의 반투명 실루엣이 남는다. 그때 플레이어의 자세를 따라 한다. */
    GHOST,
    /** 하트·별·고리·날개 같은 모양이 블록 조각들로 남는다. */
    SHAPE,
    /** 웹 에디터에서 여러 레이어를 겹쳐 꾸민 합성이 남는다. */
    CANVAS,
}
